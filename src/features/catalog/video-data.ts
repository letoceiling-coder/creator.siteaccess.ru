export const videoTemplates: VideoTemplate[] = rows.map(
  ([id, title, category, seconds, ratio, blurb, shots, genre, bpm, mood], i) => ({
    id,
    title,
    category,
    seconds,
    ratio,
    blurb,
    shots,
    music: { genre, bpm, mood },
    cover: pool[i % pool.length] ?? '',
    frames: [1, 2, 3].map((k) => pool[(i + k * 3) % pool.length] ?? ''),
  }),
)
